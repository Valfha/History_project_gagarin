/** Кликабельная «горячая точка» на SVG-схеме инфографики. */
export interface InfographicHotspot {
  /** Уникальный технический id. */
  id: string;
  /** id модуля из SHIP_MODULES, который подсвечивается при клике. */
  moduleId: string;
  /** Позиция метки на SVG в процентах ViewBox (0–100). */
  xPct: number;
  yPct: number;
}

