/** Модуль корабля Восток-3КА (для 3D-сцены и инфографики). */
export interface ShipModule {
  /** Уникальный технический id. */
  id: string;
  /** Краткое название. */
  name: string;
  /** Аббревиатура (СА, ПО, ТДУ…). */
  abbr?: string;
  /** Короткое описание (~1 строка, для тултипа/легенды). */
  shortDescription: string;
  /** Подробное описание (2–3 предложения, для панели). */
  longDescription: string;
  /** id источников из sources.ts. */
  sourceIds: ReadonlyArray<number>;
}

