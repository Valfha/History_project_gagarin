/** Географическая точка с подписью для маркера на карте. */
export interface GeoPoint {
  /** Уникальный технический id. */
  id: string;
  /** Краткое название (тултип маркера). */
  name: string;
  /** Полное название/описание (попап маркера). */
  fullName: string;
  /** Широта в градусах (WGS-84). */
  lat: number;
  /** Долгота в градусах (WGS-84). */
  lon: number;
  /** id источников из sources.ts. */
  sourceIds: ReadonlyArray<number>;
}

