/**
 * Структурированный контент раздела «Биография».
 *
 * Каждая секция содержит:
 *  - параграфы (с sourceIds для кликабельных сносок [1], [2]…),
 *  - ключевые факты (чипы с датами),
 *  - метаданные фото (url, подпись, лицензия, ссылка на источник).
 *
 * Реальные файлы изображений лежат в `public/images/biography/`.
 * До их загрузки используются плейсхолдеры — поле `placeholder: true`.
 */

export interface BiographyParagraph {
  /** Текст абзаца. Рекомендуется не разбивать на короткие предложения. */
  text: string;
  /** ID источников из `sources.ts`, подтверждающих этот абзац. */
  sourceIds: ReadonlyArray<number>;
}

export interface KeyFact {
  /** Краткая дата, например '12.10.1941' или 'май 1945'. */
  date: string;
  /** Что произошло. */
  label: string;
}

export interface BiographyPhoto {
  /** Относительный путь от base (например, 'images/biography/gagarin-1961.jpg'). */
  src: string;
  /** Подпись под фото на сайте. */
  caption: string;
  /** Краткая формулировка лицензии. */
  license: string;
  /** Прямой URL на страницу файла-источника (Wikimedia Commons и т. п.). */
  sourceUrl: string;
  /** Если файла ещё нет в репозитории — рисуем красивый плейсхолдер. */
  placeholder?: boolean;
}

export interface BiographySection {
  /** Хэш-якорь и техническое имя секции. */
  id: 'childhood' | 'education' | 'selection';
  /** Номер для штампа («01», «02», «03»). */
  number: string;
  /** Заголовок секции. */
  title: string;
  /** Подзаголовок-период, например '1934–1949'. */
  period: string;
  /** Параграфы секции. */
  paragraphs: ReadonlyArray<BiographyParagraph>;
  /** Чипы ключевых фактов (даты и события). */
  keyFacts: ReadonlyArray<KeyFact>;
  /** Подборка фотографий секции (3–4 шт.). */
  photos: ReadonlyArray<BiographyPhoto>;
}

